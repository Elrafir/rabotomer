/**
 * Хелпер для работы с файловой системой проекта «Работомер»
 *
 * Содержит утилиты для определения директории загрузки файлов ТЗ
 * и сканирования внешних рабочих директорий заказчиков.
 * Устраняет дублирование одного и того же блока кода в 6+ методах контроллера.
 */

if (!function_exists('get_upload_dir')) {
    /**
     * Определяет и возвращает полный путь к директории загрузки файлов ТЗ.
     *
     * Логика:
     * 1. Читаем настройку 'upload_dir' из Settings_model
     * 2. Если путь абсолютный (начинается с '/' или 'X:') — используем как есть
     * 3. Если путь относительный — добавляем FCPATH впереди
     * 4. Создаём директорию при необходимости
     *
     * @return string Полный абсолютный путь к директории загрузки (с trailing slash)
     */
    function get_upload_dir()
    {
        // Получаем экземпляр CI для доступа к моделям
        $CI =& get_instance();

        // Загружаем Settings_model, если ещё не загружена
        $CI->load->model('Settings_model');

        // Читаем путь из настроек, по умолчанию — 'uploads/specs/'
        $upload_dir_setting = $CI->Settings_model->get_setting('upload_dir', 'uploads/specs/');

        // Определяем тип пути: абсолютный или относительный
        // Абсолютный путь начинается с '/' (Linux/Termux) или 'X:' (Windows)
        $first_char = substr($upload_dir_setting, 0, 1);
        $second_char = substr($upload_dir_setting, 1, 1);

        if ($first_char === '/' || $second_char === ':') {
            // Абсолютный путь — просто нормализуем trailing slash
            $upload_dir = rtrim($upload_dir_setting, '/') . '/';
        } else {
            // Относительный путь — добавляем корень проекта впереди
            $upload_dir = FCPATH . rtrim($upload_dir_setting, '/') . '/';
        }

        // Создаём директорию, если она ещё не существует
        if (!is_dir($upload_dir)) {
            // Рекурсивное создание (0755 — стандартные права для веб-сервера)
            mkdir($upload_dir, 0755, true);
        }

        // Возвращаем готовый путь для использования в upload/download операциях
        return $upload_dir;
    }
}

if (!function_exists('scan_external_files')) {
    /**
     * Сканирует внешнюю директорию с рабочими материалами заказчика.
     *
     * Используется для ТЗ, у которых задан путь files_dir — папка на диске,
     * откуда заказчик кладёт рабочие файлы (макеты, ТЗ в PDF и т.д.).
     *
     * @param string $dir Абсолютный путь к директории для сканирования
     * @return array Массив файлов [['name' => ..., 'size' => ..., 'date' => ...], ...]
     *               Отсортирован по дате модификации DESC (новые сверху)
     */
    function scan_external_files($dir)
    {
        // Проверяем, что директория существует и доступна для чтения
        if (empty($dir) || !is_dir($dir) || !is_readable($dir)) {
            // Если директория недоступна — возвращаем пустой массив без ошибки
            return [];
        }

        // Массив для сбора информации о файлах
        $files = [];

        // Открываем директорию для низкоуровневого чтения (быстрее glob/scandir)
        $handle = opendir($dir);

        // Если не удалось открыть — возвращаем пустой массив
        if ($handle === false) {
            return [];
        }

        // Читаем содержимое директории поэлементно
        while (($entry = readdir($handle)) !== false) {
            // Пропускаем служебные записи текущей и родительской директории
            if ($entry === '.' || $entry === '..') {
                continue;
            }

            // Собираем полный путь к элементу
            $full_path = rtrim($dir, '/') . '/' . $entry;

            // Пропускаем поддиректории — берём только файлы
            if (is_dir($full_path)) {
                continue;
            }

            // Собираем метаданные файла для отображения в интерфейсе
            $files[] = [
                'name' => $entry,                // Имя файла
                'size' => filesize($full_path),   // Размер в байтах
                'date' => filemtime($full_path),  // Дата последней модификации (timestamp)
            ];
        }

        // Закрываем дескриптор директории для освобождения ресурсов
        closedir($handle);

        // Сортируем по дате модификации DESC (новые файлы — сверху)
        usort($files, function ($a, $b) {
            return $b['date'] - $a['date'];
        });

        // Возвращаем отсортированный список файлов
        return $files;
    }
}
